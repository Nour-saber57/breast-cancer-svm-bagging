from sklearn.model_selection import train_test_split,GridSearchCV
from sklearn.preprocessing import StandardScaler
from sklearn.ensemble import BaggingClassifier
from sklearn.svm import SVC
from sklearn.metrics import accuracy_score, classification_report, confusion_matrix
x=df.drop(columns=["diagnosis"])
y=df["diagnosis"]
#spliting the data
X_train,X_test,y_train,y_test=train_test_split(x,y,random_state=42)
#scaling the data
scalar = StandardScaler()
x_tarined_scaled=scalar.fit_transform(X_train)
x_tested_scaled=scalar.transform(X_test)

# taking object from the model
svc=SVC(random_state=42)
bag = BaggingClassifier(
    estimator=svc,
    n_jobs=-1,
    random_state=42
)


param_grid = {
    'n_estimators': [10, 25],            # number of bagged estimators
    'max_samples': [0.6, 0.8],           # fraction of samples per base estimator
    'max_features': [0.6, 0.8],          # fraction of features per base estimator
    'bootstrap': [True],                 # usually True
    # pass SVC params to the internal estimator via 'estimator__...'
    'estimator__C': [0.1, 1, 10],
    'estimator__kernel': ['rbf'],        # try 'linear' if you want faster
    'estimator__gamma': ['scale', 'auto']
}

grid=GridSearchCV (
    estimator=bag,
    param_grid=param_grid,
    cv=4, #divide the data to how many folds
    n_jobs=-1, #uses all cores
    scoring='accuracy' #find the best accuracy score
)


grid.fit(x_tarined_scaled, y_train)


y_pred = grid.predict(x_tested_scaled)

print("Test accuracy:", accuracy_score(y_test, y_pred))
print(classification_report(y_test, y_pred))
print("Confusion matrix:\n", confusion_matrix(y_test, y_pred))